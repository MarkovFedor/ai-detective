def main():
    docs_path = DATA / "documents.jsonl"
    claims_path = DATA / "claims.jsonl"
    q_path = DATA / "questions.jsonl"

    # documents
    with docs_path.open("w", encoding="utf-8") as f:
        for d in DOCS:
            f.write(json.dumps(d, ensure_ascii=False) + "\n")

    # claims — проверяем, что evidence дословно входит в документ
    docs_by_id = {d["document_id"]: d for d in DOCS}
    with claims_path.open("w", encoding="utf-8") as f:
        for cid, text, doc_id, evidence, status in CLAIMS:
            doc = docs_by_id[doc_id]
            if evidence not in doc["text"]:
                raise ValueError(f"evidence not literal in {doc_id}: {cid} -> {evidence!r}")
            f.write(json.dumps({
                "claim_id": cid,
                "text": text,
                "document_id": doc_id,
                "evidence": evidence,
                "status": status,
            }, ensure_ascii=False) + "\n")

    # вопросы
    with q_path.open("w", encoding="utf-8") as f:
        for q in QUESTIONS:
            f.write(json.dumps(q, ensure_ascii=False) + "\n")

    total_words = sum(len(d["text"].split()) for d in DOCS)
    print(f"Документов: {len(DOCS)}, всего слов: {total_words}")
    print(f"Утверждений: {len(CLAIMS)}")
    print(f"Вопросов: {len(QUESTIONS)}")
    print(f"Записано в {DATA}/")


if __name__ == "__main__":
    main()